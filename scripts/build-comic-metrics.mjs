// Deterministic advances from the bundled Comic Neue Bold WOFF; no font/parser dependency.
import { readFile, writeFile } from "node:fs/promises";
import { inflateSync } from "node:zlib";
const font = await readFile(
  "node_modules/@fontsource/comic-neue/files/comic-neue-latin-700-normal.woff",
);
const tables = {};
for (let i = 0; i < font.readUInt16BE(12); i++) {
  const at = 44 + i * 20;
  const tag = font.toString("ascii", at, at + 4);
  const offset = font.readUInt32BE(at + 4),
    length = font.readUInt32BE(at + 8),
    original = font.readUInt32BE(at + 12);
  const data = font.subarray(offset, offset + length);
  tables[tag] = length < original ? inflateSync(data) : data;
}
const cmap = tables.cmap;
let map;
for (let i = 0; i < cmap.readUInt16BE(2); i++) {
  const offset = cmap.readUInt32BE(4 + i * 8 + 4);
  if (cmap.readUInt16BE(offset) === 4) map = cmap.subarray(offset);
}
if (!map) throw new Error("Expected bundled font format-4 cmap");
const count = map.readUInt16BE(6) / 2;
function glyph(code) {
  for (let i = 0; i < count; i++) {
    const end = map.readUInt16BE(14 + i * 2),
      start = map.readUInt16BE(16 + count * 2 + i * 2);
    if (code < start || code > end) continue;
    const delta = map.readInt16BE(16 + count * 4 + i * 2),
      rangeAt = 16 + count * 6 + i * 2,
      range = map.readUInt16BE(rangeAt);
    if (!range) return (code + delta) & 65535;
    const g = map.readUInt16BE(rangeAt + range + (code - start) * 2);
    return g ? (g + delta) & 65535 : 0;
  }
  return 0;
}
const units = tables.head.readUInt16BE(18),
  metrics = tables.hhea.readUInt16BE(34),
  widths = {};
for (let code = 32; code < 65535; code++) {
  const g = glyph(code);
  if (g)
    widths[String.fromCharCode(code)] =
      tables.hmtx.readUInt16BE(Math.min(g, metrics - 1) * 4) / units;
}
// observed-write-ok: deterministic font metadata artifact, no domain mutation.
await writeFile(
  "shared/comic-metrics.ts",
  `// Generated by scripts/build-comic-metrics.mjs from bundled Comic Neue Bold (OFL).\nexport const comicAdvances: Record<string, number> = ${JSON.stringify(widths)};\n`,
);
